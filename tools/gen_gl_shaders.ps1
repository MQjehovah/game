param(
    [Parameter(Mandatory = $true)][string]$ShaderDir,
    [Parameter(Mandatory = $true)][string]$OutputHeader
)

# Build-time OpenGL shader generator.
#
# The engine authors each program ONCE in a Vulkan-flavoured GLSL file (shared
# EngineUBO + `layout(set=..,bnding=..)` samplers). This script produces the GL
# variant of those sources so both backends come from a single file:
#   - `#include "engine_ubo.glsl"` is replaced by the block's members emitted as
#     loose `uniform <type> <name>;` declarations (GL uses named uniforms),
#   - the `eng.` instance accessor is stripped,
#   - `layout(set=.., binding=..)` sampler qualifiers are dropped (GL binds
#     texture units by name via glUniform1i),
#   - fragment `in` locations are dropped so varyings link by name against the
#     (unlocated) shared GL lit vertex shader,
#   - other `#include`s are inlined.
# The result is embedded as raw strings in engine/generated/gl_shaders.hpp.
#
# Registered programs: name;fragFile (relative to ShaderDir).
$shaders = @(
    "water;water.frag"
)

$glslDelim = ")GLSL"

function Get-UboMembers([string]$uboPath) {
    $out = New-Object System.Collections.Generic.List[string]
    if (-not (Test-Path -LiteralPath $uboPath)) { return $out }
    foreach ($line in [System.IO.File]::ReadAllLines($uboPath)) {
        if ($line -match 'layout\s*\(\s*offset\s*=\s*\d+\s*\)\s*([A-Za-z_][A-Za-z0-9_]*)\s+([A-Za-z_][A-Za-z0-9_]*)(\[[0-9]+\])?\s*;') {
            $type = $matches[1]; $name = $matches[2]; $arr = $matches[3]
            if ($null -eq $arr) { $arr = "" }
            $out.Add("uniform $type $name$arr;")
        }
    }
    return $out
}

function Convert-GlSource([string]$path) {
    $dir = Split-Path -Parent $path
    $text = [System.IO.File]::ReadAllText($path)
    # Drop the Vulkan include-directive extension line (not valid on GL).
    $text = [regex]::Replace($text, '(?m)^\s*#extension\s+GL_GOOGLE_include_directive.*$', '')
    # Expand the EngineUBO include into loose uniforms.
    $uboPath = Join-Path $dir 'engine_ubo.glsl'
    $uboMembers = (Get-UboMembers $uboPath) -join "`n"
    $text = [regex]::Replace($text, '#include\s+"engine_ubo\.glsl"', { param($m) $uboMembers })
    # Inline any remaining includes.
    $text = [regex]::Replace($text, '#include\s+"([^"]+)"', {
            param($m)
            $inc = Join-Path $dir $m.Groups[1].Value
            if (Test-Path -LiteralPath $inc) { return [System.IO.File]::ReadAllText($inc) }
            return ""
        })
    # Strip the eng. accessor and Vulkan-only sampler qualifiers.
    $text = [regex]::Replace($text, '\beng\.', '')
    $text = [regex]::Replace($text, 'layout\s*\(\s*set\s*=\s*\d+\s*,\s*binding\s*=\s*\d+\s*\)\s*', '')
    # Drop location qualifiers on fragment inputs so varyings link by name.
    $text = [regex]::Replace($text, 'layout\s*\(\s*location\s*=\s*\d+\s*\)\s+(?=in\b)', '')
    if ($text.Contains($glslDelim)) {
        Write-Error "shader '$path' contains the raw-string delimiter $glslDelim"
        exit 1
    }
    return $text
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// Auto-generated by tools/gen_gl_shaders.ps1 - do not edit.")
[void]$sb.AppendLine("// Single-source GLSL (Vulkan-flavoured) transformed for the OpenGL backend.")
[void]$sb.AppendLine("#pragma once")
[void]$sb.AppendLine("namespace neon { namespace gfx { namespace gl {")

$names = @()
foreach ($entry in $shaders) {
    $parts = $entry -split ";"
    $name = $parts[0]
    $file = $parts[1]
    $names += $name
    $cap = $name.Substring(0, 1).ToUpper() + $name.Substring(1)
    $src = Convert-GlSource (Join-Path $ShaderDir $file)
    [void]$sb.AppendLine("inline constexpr const char* k${cap}Frag = R`"GLSL(")
    [void]$sb.Append($src)
    if (-not $src.EndsWith("`n")) { [void]$sb.AppendLine() }
    [void]$sb.AppendLine(")GLSL`";")
}

[void]$sb.AppendLine("} } } // namespace neon::gfx::gl")

$dirOut = Split-Path -Parent $OutputHeader
if ($dirOut -and -not (Test-Path $dirOut)) {
    New-Item -ItemType Directory -Force -Path $dirOut | Out-Null
}
[System.IO.File]::WriteAllText($OutputHeader, $sb.ToString())
Write-Host "Wrote $OutputHeader ($($shaders.Count) GL shader programs)"
